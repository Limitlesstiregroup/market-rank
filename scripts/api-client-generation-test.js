const assert = require('assert');
const path = require('path');
const fs = require('fs');
const { createMarketRankClient } = require('../web/api-client.js');

async function run() {
  const clientPath = path.join(__dirname, '..', 'web', 'api-client.js');
  const content = fs.readFileSync(clientPath, 'utf8');
  assert.ok(content.includes('Auto-generated by scripts/generate-api-client.js'));

  const calls = [];
  global.fetch = async (url, options) => {
    calls.push({ url, options });
    return {
      ok: true,
      status: 200,
      async json() {
        return { ok: true };
      }
    };
  };

  const client = createMarketRankClient({
    baseUrl: 'http://127.0.0.1:4510',
    token: 'abc-token',
    moderatorKey: 'mod-key'
  });

  await client.login({ email: 'user@test.com', password: 'StrongPass123!' });
  await client.health();
  await client.metrics();

  assert.equal(calls.length, 3);
  assert.equal(calls[0].url, 'http://127.0.0.1:4510/api/auth/login');
  assert.equal(calls[0].options.method, 'POST');
  assert.equal(calls[0].options.headers.authorization, 'Bearer abc-token');

  assert.equal(calls[1].url, 'http://127.0.0.1:4510/api/health');
  assert.equal(calls[1].options.method, 'GET');

  assert.equal(calls[2].url, 'http://127.0.0.1:4510/api/metrics');
  assert.equal(calls[2].options.headers['x-moderator-key'], 'mod-key');

  assert.equal(typeof client.register, 'function');
  assert.equal(typeof client.createPrediction, 'function');
  assert.equal(typeof client.moderationDashboard, 'function');

  console.log('market-rank api client generation test passed');
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
