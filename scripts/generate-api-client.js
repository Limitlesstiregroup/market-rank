const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const specPath = path.join(root, 'docs', 'openapi.json');
const outPath = path.join(root, 'web', 'api-client.js');

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));

const operationNames = {
  'GET /api/health': 'health',
  'GET /api/metrics': 'metrics',
  'POST /api/auth/register': 'register',
  'POST /api/auth/login': 'login',
  'POST /api/auth/logout': 'logout',
  'POST /api/auth/email/verify/request': 'requestEmailVerification',
  'POST /api/auth/email/verify/confirm': 'confirmEmailVerification',
  'POST /api/auth/password/reset/request': 'requestPasswordReset',
  'POST /api/auth/password/reset/confirm': 'confirmPasswordReset',
  'POST /api/predictions': 'createPrediction',
  'POST /api/moderation/flag': 'createFlag',
  'POST /api/moderation/ban': 'createBan',
  'POST /api/moderation/appeal': 'createAppeal',
  'GET /api/moderation/dashboard': 'moderationDashboard',
  'GET /api/leaderboard': 'leaderboard'
};

const operations = [];
for (const route of Object.keys(spec.paths || {})) {
  const pathItem = spec.paths[route];
  for (const method of Object.keys(pathItem || {})) {
    const key = `${method.toUpperCase()} ${route}`;
    const name = operationNames[key];
    if (!name) continue;
    operations.push({
      name,
      method: method.toUpperCase(),
      route,
      requiresAuth: Boolean((pathItem[method].security || []).find((s) => s.bearerAuth)),
      requiresModeratorKey: Boolean((pathItem[method].security || []).find((s) => s.moderatorKey))
    });
  }
}

operations.sort((a, b) => a.name.localeCompare(b.name));

const methodBlocks = operations.map((op) => {
  const bodyArg = op.method === 'GET' ? '' : 'body = {}';
  const sig = bodyArg ? `${bodyArg}, options = {}` : 'options = {}';
  const reqBodyArg = op.method === 'GET' ? 'undefined' : 'body';
  const docs = [
    '  /**',
    `   * ${op.method} ${op.route}`,
    op.requiresAuth ? '   * Requires bearer auth token.' : '   * Public endpoint.',
    op.requiresModeratorKey ? '   * Requires moderator key.' : '',
    '   */'
  ].filter(Boolean).join('\n');
  return `${docs}\n  async ${op.name}(${sig}) {\n    return request('${op.method}', '${op.route}', ${reqBodyArg}, options);\n  }`;
}).join(',\n\n');

const content = [
  '// Auto-generated by scripts/generate-api-client.js.',
  '// Do not edit manually. Regenerate via: node scripts/generate-api-client.js',
  '',
  '(function (globalScope) {',
  "  'use strict';",
  '',
  '  function createMarketRankClient(config = {}) {',
  "    const baseUrl = String(config.baseUrl || '').replace(/\\\/$/, '');",
  "    let token = config.token || '';",
  "    let moderatorKey = config.moderatorKey || '';",
  '',
  '    async function request(method, route, body, options = {}) {',
  '      const headers = {',
  '        ...(options.headers || {}),',
  "        'content-type': 'application/json'",
  '      };',
  '',
  '      const authToken = options.token || token;',
  "      if (authToken) headers.authorization = 'Bearer ' + authToken;",
  '',
  '      const modKey = options.moderatorKey || moderatorKey;',
  "      if (modKey) headers['x-moderator-key'] = modKey;",
  '',
  '      const url = baseUrl + route;',
  '      const res = await fetch(url, {',
  '        method,',
  '        headers,',
  '        body: body === undefined ? undefined : JSON.stringify(body)',
  '      });',
  '',
  '      let json = null;',
  '      try {',
  '        json = await res.json();',
  '      } catch (_) {',
  '        json = null;',
  '      }',
  '',
  '      if (!res.ok) {',
  "        const error = new Error((json && json.error) || ('Request failed: ' + res.status));",
  '        error.status = res.status;',
  '        error.payload = json;',
  '        throw error;',
  '      }',
  '',
  '      return json;',
  '    }',
  '',
  '    return {',
  "      setToken(nextToken) { token = nextToken || ''; },",
  "      setModeratorKey(nextKey) { moderatorKey = nextKey || ''; },",
  '',
  methodBlocks,
  '    };',
  '  }',
  '',
  "  if (typeof module !== 'undefined' && module.exports) {",
  '    module.exports = { createMarketRankClient };',
  '  } else {',
  '    globalScope.createMarketRankClient = createMarketRankClient;',
  '  }',
  "})(typeof globalThis !== 'undefined' ? globalThis : window);",
  ''
].join('\n');

fs.writeFileSync(outPath, content);
console.log(`Generated ${path.relative(root, outPath)} with ${operations.length} operations.`);
